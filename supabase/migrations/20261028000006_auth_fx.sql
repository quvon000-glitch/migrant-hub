-- Sign-in attempts (edge function only) and the exchange-rate snapshot the app reads in one call
create table public.login_attempts (
  id bigint generated by default as identity primary key,
  phone text not null,
  success boolean not null default false,
  attempted_at timestamptz not null default now()
);
create index login_attempts_phone on public.login_attempts (phone, attempted_at desc);
alter table public.login_attempts enable row level security; -- no policies: service role only

-- so'm per unit (Central Bank of Uzbekistan), rubles per unit (Bank of Russia), NBU buy/sell, RUB history
create or replace function public.fx_snapshot() returns jsonb
language sql stable security definer set search_path = '' as $$
  with latest as (
    select source, max(rate_date) d from public.fx_rates group by source
  ), cur as (
    select f.* from public.fx_rates f join latest l on l.source = f.source and l.d = f.rate_date
  )
  select case when not exists (select 1 from cur where source = 'cbu') then null else jsonb_build_object(
    'date', (select d from latest where source = 'cbu'),
    'rates', (select jsonb_object_agg(ccy, jsonb_build_object('rate', rate, 'diff', diff)) from cur where source = 'cbu'),
    'fetched_at', (select max(fetched_at) from cur where source = 'cbu'),
    'rub_history', (select jsonb_agg(jsonb_build_object('date', rate_date, 'rate', rate) order by rate_date)
                    from (select rate_date, rate from public.fx_rates where source = 'cbu' and ccy = 'RUB' order by rate_date desc limit 8) h),
    'cbr', (select jsonb_build_object('date', (select d from latest where source = 'cbr'),
              'rates', jsonb_object_agg(ccy, jsonb_build_object('rate', rate, 'diff', diff))) from cur where source = 'cbr'),
    'nbu', (select jsonb_build_object('date', (select d from latest where source = 'nbu_cash'),
              'cash', (select jsonb_object_agg(ccy, jsonb_build_object('buy', rate, 'sell', sell)) from cur where source = 'nbu_cash'),
              'app', (select jsonb_object_agg(ccy, jsonb_build_object('buy', rate, 'sell', sell)) from cur where source = 'nbu_app')))
  ) end;
$$;
grant execute on function public.fx_snapshot() to anon, authenticated;
