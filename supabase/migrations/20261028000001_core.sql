-- Core: extensions, profiles, roles, news, broadcasts, fx rates
create extension if not exists pg_trgm with schema extensions;

-- ---------- profiles ----------
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  phone text not null unique,
  display_name text not null check (char_length(display_name) between 1 and 60),
  last_name text check (char_length(last_name) <= 60),
  username text unique check (username ~ '^[a-zA-Z][a-zA-Z0-9_]{4,31}$'),
  avatar_url text,
  about text check (char_length(about) <= 300),
  phone_visible boolean not null default false,
  birth_date date,
  birth_place text,
  citizenship text,
  current_city text,
  recovery_email text,
  chat_city text check (chat_city in ('moskva', 'spb')),
  role text not null default 'user' check (role in ('user', 'admin')),
  blocked_at timestamptz,
  blocked_reason text,
  reset_requested_at timestamptz,
  terms_accepted_at timestamptz,
  last_seen_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index profiles_username_lower on public.profiles (lower(username));

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

-- New auth user -> profile (data comes from the auth-register edge function)
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
declare m jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
begin
  insert into public.profiles (id, phone, display_name, last_name, birth_date, citizenship, current_city, recovery_email, terms_accepted_at)
  values (
    new.id,
    coalesce(m->>'phone', split_part(new.email, '@', 1)),
    coalesce(nullif(m->>'display_name', ''), 'Foydalanuvchi'),
    nullif(m->>'last_name', ''),
    nullif(m->>'birth_date', '')::date,
    nullif(m->>'citizenship', ''),
    nullif(m->>'current_city', ''),
    nullif(m->>'recovery_email', ''),
    now()
  );
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Users may edit their own profile but never role / block / phone fields
create or replace function public.profiles_guard() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is not null and not public.is_admin() then
    new.role := old.role;
    new.blocked_at := old.blocked_at;
    new.blocked_reason := old.blocked_reason;
    new.phone := old.phone;
    new.reset_requested_at := old.reset_requested_at;
    new.created_at := old.created_at;
  end if;
  new.updated_at := now();
  return new;
end $$;
create trigger profiles_guard before update on public.profiles
  for each row execute function public.profiles_guard();

alter table public.profiles enable row level security;
create policy "own profile read" on public.profiles for select to authenticated using (id = (select auth.uid()) or (select public.is_admin()));
create policy "own profile update" on public.profiles for update to authenticated using (id = (select auth.uid()) or (select public.is_admin())) with check (id = (select auth.uid()) or (select public.is_admin()));

-- What other members may see (phone only when the owner allows it)
create or replace view public.public_profiles with (security_invoker = false) as
  select id, display_name, last_name, username, avatar_url, about,
         case when phone_visible then '+' || phone end as phone,
         role = 'admin' as is_admin, last_seen_at, created_at
  from public.profiles where blocked_at is null;
revoke all on public.public_profiles from anon;
grant select on public.public_profiles to authenticated;

-- ---------- news ----------
create table public.news_items (
  id bigint generated by default as identity primary key,
  source text not null,
  external_id text not null,
  url text not null,
  original_title text not null,
  title text,
  summary text,
  body text,
  tag text,
  image_url text,
  relevant boolean not null default false,
  pinned_at timestamptz,
  hidden_at timestamptz,
  published_at timestamptz not null,
  created_at timestamptz not null default now(),
  unique (source, external_id)
);
create index news_feed_idx on public.news_items (published_at desc) where relevant and hidden_at is null;
alter table public.news_items enable row level security;
create policy "news readable" on public.news_items for select to anon, authenticated using (relevant and hidden_at is null or (select public.is_admin()));
create policy "admin writes news" on public.news_items for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

-- ---------- broadcasts (admin announcements) ----------
create table public.broadcasts (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  created_by uuid references public.profiles (id) on delete set null,
  deleted_at timestamptz,
  created_at timestamptz not null default now()
);
alter table public.broadcasts enable row level security;
create policy "broadcasts readable" on public.broadcasts for select to authenticated using (deleted_at is null or (select public.is_admin()));
create policy "admin writes broadcasts" on public.broadcasts for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

-- ---------- fx rates ----------
create table public.fx_rates (
  ccy text not null,
  source text not null default 'cbr',
  rate numeric not null,
  diff numeric not null default 0,
  sell numeric,
  rate_date date not null,
  fetched_at timestamptz not null default now(),
  primary key (source, ccy, rate_date)
);
alter table public.fx_rates enable row level security;
create policy "fx readable" on public.fx_rates for select to anon, authenticated using (true);

-- ---------- realtime ----------
alter publication supabase_realtime add table public.news_items, public.broadcasts;
