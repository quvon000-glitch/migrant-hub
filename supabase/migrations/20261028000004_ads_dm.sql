-- Marketplace ads, favorites, ad chats (direct messages), blocks and reports
create table public.ads (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  category text not null check (category in ('Ish', 'Uy-joy', 'Transport', 'Maishiy xizmatlar')),
  title text not null check (char_length(title) between 3 and 120),
  amount int check (amount is null or amount between 0 and 1000000000),
  price_text text not null default 'Kelishiladi',
  city text not null default '' check (char_length(city) <= 80),
  address text not null default '' check (char_length(address) <= 160),
  description text not null default '' check (char_length(description) <= 4000),
  attrs jsonb not null default '{}'::jsonb,
  photos jsonb not null default '[]'::jsonb check (jsonb_typeof(photos) = 'array' and jsonb_array_length(photos) <= 5),
  telegram text,
  whatsapp text,
  status text not null default 'active' check (status in ('active', 'archived')),
  views int not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index ads_active_created on public.ads (created_at desc) where status = 'active';
create index ads_user on public.ads (user_id);

create or replace function public.format_rub(n int) returns text
language sql immutable set search_path = '' as $$
  select replace(trim(to_char(n, 'FM999G999G999G999')), ',', ' ');
$$;

-- Keeps only the fields of the category, builds the price label, checks contacts and limits
create or replace function public.ads_before_write() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  allowed text[];
  clean jsonb := '{}'::jsonb;
  k text; v text;
  active_count int;
  tg text; wa text;
begin
  allowed := case new.category
    when 'Ish' then array['company', 'jobType', 'type', 'schedule', 'experience']
    when 'Uy-joy' then array['housingType', 'deal', 'rooms']
    when 'Transport' then array['vehicleType', 'make', 'model', 'year']
    else array['serviceType', 'serviceMode'] end;
  if jsonb_typeof(new.attrs) = 'object' then
    for k, v in select key, trim(value) from jsonb_each_text(new.attrs) loop
      if k = any (allowed) and v <> '' then clean := clean || jsonb_build_object(k, left(v, 80)); end if;
    end loop;
  end if;
  new.attrs := clean;
  if new.amount is not null and new.amount <= 0 then new.amount := null; end if;
  new.price_text := case
    when new.amount is null then 'Kelishiladi'
    when new.category = 'Ish' then public.format_rub(new.amount) || ' ₽ / oy'
    when new.category = 'Maishiy xizmatlar' then public.format_rub(new.amount) || ' ₽ dan'
    when new.category = 'Uy-joy' and clean->>'deal' = 'Ijara' then public.format_rub(new.amount) || ' ₽ / oy'
    when new.category = 'Uy-joy' and clean->>'deal' = 'Kunlik ijara' then public.format_rub(new.amount) || ' ₽ / kun'
    else public.format_rub(new.amount) || ' ₽' end;

  if nullif(trim(new.telegram), '') is not null then
    tg := regexp_replace(regexp_replace(trim(new.telegram), '^https?://(t\.me|telegram\.me)/', '', 'i'), '^@', '');
    tg := split_part(split_part(tg, '/', 1), '?', 1);
    if tg !~ '^[A-Za-z0-9_]{4,32}$' then perform public.raise_user_error('Telegram foydalanuvchi nomi noto‘g‘ri (masalan: @ism_familiya)'); end if;
    new.telegram := tg;
  else
    new.telegram := null;
  end if;
  if nullif(trim(new.whatsapp), '') is not null then
    wa := regexp_replace(new.whatsapp, '\D', '', 'g');
    if char_length(wa) not between 10 and 15 then perform public.raise_user_error('WhatsApp raqami noto‘g‘ri'); end if;
    new.whatsapp := wa;
  else
    new.whatsapp := null;
  end if;

  if tg_op = 'INSERT' then
    if auth.uid() is not null then new.user_id := auth.uid(); end if;
    new.views := 0;
    new.created_at := now();
    select count(*) into active_count from public.ads where user_id = new.user_id and status = 'active';
    if active_count >= 30 then perform public.raise_user_error('Bir vaqtda ko‘pi bilan 30 ta faol e’lon bo‘lishi mumkin'); end if;
  else
    new.user_id := old.user_id;
    new.created_at := old.created_at;
    if not public.is_admin() then new.views := old.views; end if;
  end if;
  new.updated_at := now();
  return new;
end $$;
create trigger ads_before_write before insert or update on public.ads
  for each row execute function public.ads_before_write();

alter table public.ads enable row level security;
create policy "ads readable" on public.ads for select to anon, authenticated
  using (status = 'active' or user_id = (select auth.uid()) or (select public.is_admin()));
create policy "own ads insert" on public.ads for insert to authenticated
  with check (user_id = (select auth.uid()) and not exists (select 1 from public.profiles where id = (select auth.uid()) and blocked_at is not null));
create policy "own ads update" on public.ads for update to authenticated
  using (user_id = (select auth.uid()) or (select public.is_admin())) with check (user_id = (select auth.uid()) or (select public.is_admin()));
create policy "own ads delete" on public.ads for delete to authenticated using (user_id = (select auth.uid()) or (select public.is_admin()));

create or replace function public.ad_view(p_id bigint) returns void
language sql security definer set search_path = '' as $$
  update public.ads set views = views + 1 where id = p_id and status = 'active' and user_id <> coalesce(auth.uid(), '00000000-0000-0000-0000-000000000000');
$$;

