-- ---------- blocks & reports ----------
create table public.user_blocks (
  blocker_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  blocked_id uuid not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker_id, blocked_id),
  check (blocker_id <> blocked_id)
);
alter table public.user_blocks enable row level security;
create policy "own blocks" on public.user_blocks for all to authenticated using (blocker_id = (select auth.uid())) with check (blocker_id = (select auth.uid()));

create or replace function public.is_blocked_between(a uuid, b uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.user_blocks where (blocker_id = a and blocked_id = b) or (blocker_id = b and blocked_id = a));
$$;

create table public.user_reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  target_user_id uuid references public.profiles (id) on delete cascade,
  ad_id bigint references public.ads (id) on delete set null,
  conversation_id bigint,
  reason text not null check (char_length(reason) <= 200),
  created_at timestamptz not null default now()
);
alter table public.user_reports enable row level security;
create policy "report as myself" on public.user_reports for insert to authenticated with check (reporter_id = (select auth.uid()));
create policy "admin reads reports" on public.user_reports for select to authenticated using ((select public.is_admin()));

-- ---------- conversations (one per ad + buyer) ----------
create table public.conversations (
  id bigint generated by default as identity primary key,
  ad_id bigint references public.ads (id) on delete set null,
  ad_title text not null default '',
  buyer_id uuid not null references public.profiles (id) on delete cascade,
  seller_id uuid not null references public.profiles (id) on delete cascade,
  buyer_read_at timestamptz not null default now(),
  seller_read_at timestamptz not null default now(),
  buyer_hidden_at timestamptz,
  seller_hidden_at timestamptz,
  last_message text,
  last_sender_id uuid,
  last_message_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  unique (ad_id, buyer_id)
);
create index conversations_buyer on public.conversations (buyer_id, last_message_at desc);
create index conversations_seller on public.conversations (seller_id, last_message_at desc);
alter table public.conversations enable row level security;
create policy "participants read conversation" on public.conversations for select to authenticated
  using (buyer_id = (select auth.uid()) or seller_id = (select auth.uid()));

create table public.dm_messages (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.conversations (id) on delete cascade,
  sender_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  client_id uuid,
  body text not null check (char_length(trim(body)) between 1 and 2000),
  reply_to_id bigint references public.dm_messages (id) on delete set null,
  edited_at timestamptz,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  unique (sender_id, client_id)
);
create index dm_messages_conv on public.dm_messages (conversation_id, id desc);
alter table public.dm_messages enable row level security;

create or replace function public.is_participant(p_conv bigint) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.conversations where id = p_conv and (buyer_id = auth.uid() or seller_id = auth.uid()));
$$;

create policy "participants read messages" on public.dm_messages for select to authenticated
  using ((select public.is_participant(conversation_id)));
create policy "participants send messages" on public.dm_messages for insert to authenticated
  with check (sender_id = (select auth.uid()) and (select public.is_participant(conversation_id)));

-- New message: block check, conversation summary, sender has read everything up to now
create or replace function public.dm_before_insert() returns trigger
language plpgsql security definer set search_path = '' as $$
declare c record;
begin
  select * into c from public.conversations where id = new.conversation_id;
  if public.is_blocked_between(c.buyer_id, c.seller_id) then
    perform public.raise_user_error('Bu foydalanuvchiga xabar yuborib bo‘lmaydi');
  end if;
  if exists (select 1 from public.profiles where id = new.sender_id and blocked_at is not null) then
    perform public.raise_user_error('Hisobingiz bloklangan');
  end if;
  new.body := trim(new.body);
  new.created_at := now();
  new.edited_at := null;
  new.deleted_at := null;
  return new;
end $$;
create trigger dm_before_insert before insert on public.dm_messages
  for each row execute function public.dm_before_insert();

create or replace function public.dm_after_insert() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  update public.conversations set
    last_message = left(new.body, 200),
    last_sender_id = new.sender_id,
    last_message_at = new.created_at,
    buyer_read_at = case when buyer_id = new.sender_id then new.created_at else buyer_read_at end,
    seller_read_at = case when seller_id = new.sender_id then new.created_at else seller_read_at end
  where id = new.conversation_id;
  return null;
end $$;
create trigger dm_after_insert after insert on public.dm_messages
  for each row execute function public.dm_after_insert();

create or replace function public.conversation_start(p_ad bigint) returns bigint
language plpgsql security definer set search_path = '' as $$
declare uid uuid := auth.uid(); a record; cid bigint;
begin
  if uid is null then perform public.raise_user_error('Avval hisobga kiring'); end if;
  select id, user_id, status, title into a from public.ads where id = p_ad;
  if not found then perform public.raise_user_error('E’lon topilmadi'); end if;
  if a.user_id = uid then perform public.raise_user_error('Bu sizning e’loningiz'); end if;
  select id into cid from public.conversations where ad_id = p_ad and buyer_id = uid;
  if found then
    update public.conversations set buyer_hidden_at = null where id = cid and buyer_hidden_at is not null and last_message_at <= buyer_hidden_at;
    return cid;
  end if;
  if a.status <> 'active' then perform public.raise_user_error('E’lon faol emas'); end if;
  if public.is_blocked_between(uid, a.user_id) then perform public.raise_user_error('Bu foydalanuvchiga yozib bo‘lmaydi'); end if;
  insert into public.conversations (ad_id, ad_title, buyer_id, seller_id) values (p_ad, a.title, uid, a.user_id)
    on conflict (ad_id, buyer_id) do update set ad_title = excluded.ad_title
    returning id into cid;
  return cid;
end $$;

create or replace function public.conversation_read(p_conv bigint) returns timestamptz
language sql security definer set search_path = '' as $$
  update public.conversations set
    buyer_read_at = case when buyer_id = auth.uid() then now() else buyer_read_at end,
    seller_read_at = case when seller_id = auth.uid() then now() else seller_read_at end
  where id = p_conv and (buyer_id = auth.uid() or seller_id = auth.uid())
  returning now();
$$;

-- "Delete chat for me": earlier messages stay hidden for this user only
create or replace function public.conversation_hide(p_conv bigint) returns void
language sql security definer set search_path = '' as $$
  update public.conversations set
    buyer_hidden_at = case when buyer_id = auth.uid() then now() else buyer_hidden_at end,
    seller_hidden_at = case when seller_id = auth.uid() then now() else seller_hidden_at end
  where id = p_conv and (buyer_id = auth.uid() or seller_id = auth.uid());
$$;

-- Own message: edit within 48 hours or delete for everyone (row stays, text wiped)
create or replace function public.dm_action(p_id bigint, p_action text, p_body text default null) returns void
language plpgsql security definer set search_path = '' as $$
declare m record; b text := trim(coalesce(p_body, ''));
begin
  select * into m from public.dm_messages where id = p_id and deleted_at is null;
  if not found or m.sender_id <> auth.uid() then perform public.raise_user_error('Xabar topilmadi'); end if;
  if p_action = 'edit' then
    if b = '' or char_length(b) > 2000 then perform public.raise_user_error('Xabar bo‘sh'); end if;
    if m.created_at < now() - interval '48 hours' then perform public.raise_user_error('48 soatdan eski xabarni tahrirlab bo‘lmaydi'); end if;
    update public.dm_messages set body = b, edited_at = now() where id = p_id;
  elsif p_action = 'delete' then
    update public.dm_messages set body = '—', deleted_at = now() where id = p_id;
  else
    perform public.raise_user_error('Noma’lum amal');
  end if;
end $$;

-- Inbox: one call returns everything the list needs
create or replace function public.chat_list() returns table (
  id bigint, ad_id bigint, ad_title text, ad_photo text, ad_price_text text, ad_active boolean,
  other_user_id uuid, other_name text, other_avatar text, i_am_seller boolean,
  last_message text, last_message_at timestamptz, last_from_me boolean, unread int, other_read_at timestamptz, blocked_by_me boolean
)
language sql stable security definer set search_path = '' as $$
  select c.id, c.ad_id, coalesce(a.title, c.ad_title), a.photos->>0, coalesce(a.price_text, ''), coalesce(a.status = 'active', false),
    o.id, coalesce(o.display_name, 'Foydalanuvchi'), o.avatar_url, c.seller_id = auth.uid(),
    c.last_message, c.last_message_at, c.last_sender_id = auth.uid(),
    (select count(*)::int from public.dm_messages m where m.conversation_id = c.id and m.sender_id <> auth.uid() and m.deleted_at is null
       and m.created_at > greatest(case when c.seller_id = auth.uid() then c.seller_read_at else c.buyer_read_at end,
                                   coalesce(case when c.seller_id = auth.uid() then c.seller_hidden_at else c.buyer_hidden_at end, '-infinity'))),
    case when c.seller_id = auth.uid() then c.buyer_read_at else c.seller_read_at end,
    exists (select 1 from public.user_blocks b where b.blocker_id = auth.uid() and b.blocked_id = o.id)
  from public.conversations c
  left join public.ads a on a.id = c.ad_id
  left join public.profiles o on o.id = case when c.seller_id = auth.uid() then c.buyer_id else c.seller_id end
  where (c.buyer_id = auth.uid() or c.seller_id = auth.uid())
    and c.last_message is not null
    and c.last_message_at > coalesce(case when c.seller_id = auth.uid() then c.seller_hidden_at else c.buyer_hidden_at end, '-infinity')
  order by c.last_message_at desc
  limit 200;
$$;

