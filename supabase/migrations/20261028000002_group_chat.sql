-- City group chats (Moskva / Sankt-Peterburg): messages, moderation, bans, read receipts
create table public.group_messages (
  id bigint generated by default as identity primary key,
  city text not null check (city in ('moskva', 'spb')),
  user_id uuid not null references public.profiles (id) on delete cascade,
  client_id uuid,
  kind text not null default 'text' check (kind in ('text', 'image', 'video', 'voice')),
  body text not null default '' check (char_length(body) <= 2000),
  media_path text,
  thumb_path text,
  duration_sec int,
  width int,
  height int,
  media_expired boolean not null default false,
  reply_to_id bigint references public.group_messages (id) on delete set null,
  body_hash text,
  pinned_at timestamptz,
  hidden_at timestamptz,
  report_count int not null default 0,
  edited_at timestamptz,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  unique (user_id, client_id)
);
create index group_messages_city_id on public.group_messages (city, id desc);
create index group_messages_user_day on public.group_messages (user_id, created_at desc);
create index group_messages_reply on public.group_messages (reply_to_id);
create index group_messages_body_trgm on public.group_messages using gin (body extensions.gin_trgm_ops);

create table public.group_members (
  user_id uuid primary key references public.profiles (id) on delete cascade,
  city text not null check (city in ('moskva', 'spb')),
  last_read_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index group_members_city on public.group_members (city);

create table public.group_saved (
  user_id uuid not null references public.profiles (id) on delete cascade,
  message_id bigint not null references public.group_messages (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, message_id)
);

create table public.group_reports (
  message_id bigint not null references public.group_messages (id) on delete cascade,
  reporter_id uuid not null references public.profiles (id) on delete cascade,
  reason text not null,
  created_at timestamptz not null default now(),
  primary key (message_id, reporter_id)
);

create table public.chat_bans (
  user_id uuid primary key references public.profiles (id) on delete cascade,
  until timestamptz,
  reason text not null,
  created_at timestamptz not null default now()
);

create table public.chat_strikes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  rule text not null,
  excerpt text not null default '',
  created_at timestamptz not null default now()
);
create index chat_strikes_user on public.chat_strikes (user_id);

create table public.banned_phones (
  phone text primary key,
  reason text not null,
  created_at timestamptz not null default now()
);

