-- Deleted messages keep their row (text and media are wiped) so the deletion reaches
-- every open chat through Realtime. Writes only go through the RPCs below.
create policy "members read live messages" on public.group_messages for select to authenticated
  using (created_at > now() - interval '48 hours' or pinned_at is not null);
create policy "members read membership" on public.group_members for select to authenticated using (true);
create policy "own saved" on public.group_saved for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy "admin reads reports" on public.group_reports for select to authenticated using ((select public.is_admin()));
create policy "own or admin bans" on public.chat_bans for select to authenticated using (user_id = (select auth.uid()) or (select public.is_admin()));
create policy "admin strikes" on public.chat_strikes for select to authenticated using ((select public.is_admin()));
create policy "admin banned phones" on public.banned_phones for select to authenticated using ((select public.is_admin()));

-- ---------- helpers ----------
create or replace function public.moscow_day_start() returns timestamptz
language sql stable set search_path = '' as $$
  select (date_trunc('day', now() at time zone 'Europe/Moscow')) at time zone 'Europe/Moscow';
$$;

create or replace function public.norm_text(t text) returns text
language sql immutable set search_path = '' as $$
  select regexp_replace(replace(translate(lower(coalesce(t, '')), '‘’ʻʼ`´', ''''''''''''), 'ё', 'е'), '\s+', ' ', 'g');
$$;

create or replace function public.amount_value(raw text) returns numeric
language plpgsql immutable set search_path = '' as $$
declare s text := lower(trim(raw)); m text[];
begin
  m := regexp_match(s, '^(\d{1,3})\s*(к|k|тыс\.?|тысяч|ming|минг)$');
  if m is not null then return m[1]::numeric * 1000; end if;
  s := regexp_replace(s, '[ .,]', '', 'g');
  if s ~ '^\d+$' then return s::numeric; end if;
  return 0;
end $$;

-- Rule-based content filter. Returns the broken rule ('card' | 'pay' | 'sex') or null.
create or replace function public.moderate_text(t text) returns text
language plpgsql immutable set search_path = '' as $$
declare
  n text := public.norm_text(t);
  amount text := '(\d{1,3}(?:[ .,]\d{3})+|\d{4,6}|\d{1,3}\s*(?:к|k|тыс\.?|тысяч|ming|минг)(?![[:alpha:]]))';
  day text := '(в день|в сутки|за день|/день|/сут|за смену|в смену|ежедневн|kuniga|kunlik|bir kunga|har kuni|кунига|кунлик|бир кунга|ҳар куни|хар куни|smena|смена|сутки)';
  monthly text := '(oy|ой|месяц|мес\.?(?![[:alpha:]]))';
  m text[];
  v numeric;
begin
  if n = '' then return null; end if;
  if n ~ '(интим|эскорт|escort|проститу|fohish|фоҳиш|фохиш|jalab|жалаб|индивидуалк|секс[ -]?услуг|досуг для мужчин|intim xizmat|интим хизмат|18\+ ?услуг)' then
    return 'sex';
  end if;
  -- "10 000 ₽ в день": amount, gap, day word; a month word in the gap means a monthly salary
  for m in select regexp_matches(n, amount || '([^\d\n]{0,25})' || day, 'g') loop
    if m[2] ~ monthly then continue; end if;
    v := public.amount_value(m[1]);
    if v > 8000 and v < 200000 then return 'pay'; end if;
  end loop;
  for m in select regexp_matches(n, day || '([^\d\n]{0,25})' || amount, 'g') loop
    if m[2] ~ monthly then continue; end if;
    v := public.amount_value(m[3]);
    if v > 8000 and v < 200000 then return 'pay'; end if;
  end loop;
  if n ~ '(карт|karta|kart[aoy]|plastik|пластик)'
     and n ~ '(куп(лю|им|ит|ля)|скуп|прода(м|ю|ём|ем|жа)|при[её]м|аренд|сда(м|ть|ём|ем)|оформ(лю|им|ить|ляем)|olam(an|iz)|sotib ol|sotam(an|iz)|ijaraga|оламиз|оламан|сотиб ол|сотам(ан|из)|ижарага|kerak|керак)'
     and n !~ '(тройк|подорожник|транспортн|patent|патент|sim|сим[- ]?карт|скидочн|миграционн)'
     and n ~ '(банк|сбер|тинь|т-банк|тбанк|втб|альфа|озон\s*банк|дебет|дроп|обнал|на (ваше|свое|твое) имя|bank|debet|drop|ismingizga|исмингизга|o''z nomingizga|ўз номингизга)' then
    return 'card';
  end if;
  return null;
end $$;

create or replace function public.rule_text(rule text) returns text
language sql immutable set search_path = '' as $$
  select case rule
    when 'card' then 'Bank kartasi bilan bog‘liq e’lonlar taqiqlangan'
    when 'pay' then 'Kunlik 8 000 ₽ dan yuqori ish haqi va’da qilingan e’lonlar taqiqlangan'
    when 'sex' then 'Fohishabozlik va intim xizmatlar reklamasi taqiqlangan'
    else 'Chat qoidalari buzildi' end;
$$;

create or replace function public.has_link(t text) returns boolean
language sql immutable set search_path = '' as $$
  select coalesce(t, '') ~* '(https?://|www\.|t\.me/|telegram\.me/|wa\.me/|[a-z0-9-]{2,}\.(ru|com|uz|net|org|me|io|su|info|site|online|xyz|рф)(?![[:alnum:]]))';
$$;

create or replace function public.ban_text(p_until timestamptz, p_reason text) returns text
language sql stable set search_path = '' as $$
  select case when p_until is null then 'Siz chatdan doimiy chetlatilgansiz. Sabab: ' || p_reason
    else 'Siz ' || to_char(p_until at time zone 'Europe/Moscow', 'DD.MM "soat" HH24:MI') || ' gacha chatga yoza olmaysiz. Sabab: ' || p_reason end;
$$;

create or replace function public.active_ban_text(p_user uuid) returns text
language sql stable security definer set search_path = '' as $$
  select public.ban_text(until, reason) from public.chat_bans
  where user_id = p_user and (until is null or until > now());
$$;

-- 1st: warning, 2nd: 24 h, 3rd: 7 days, 4th (or certain sex ad): permanent + phone banned.
create or replace function public.apply_strike(p_user uuid, p_rule text, p_excerpt text, p_certain boolean) returns text
language plpgsql security definer set search_path = '' as $$
declare cnt int; reason text := public.rule_text(p_rule); ph text;
begin
  insert into public.chat_strikes (user_id, rule, excerpt) values (p_user, p_rule, left(coalesce(p_excerpt, ''), 300));
  select count(*) into cnt from public.chat_strikes where user_id = p_user;
  if (p_rule = 'sex' and p_certain) or cnt >= 4 then
    insert into public.chat_bans (user_id, until, reason) values (p_user, null, reason)
      on conflict (user_id) do update set until = null, reason = excluded.reason, created_at = now();
    select phone into ph from public.profiles where id = p_user;
    if ph is not null then insert into public.banned_phones (phone, reason) values (ph, reason) on conflict do nothing; end if;
    return reason || '. Siz chatdan doimiy chetlatildingiz.';
  elsif cnt = 1 then
    return reason || '. Xabar yuborilmadi. Bu birinchi ogohlantirish — keyingi buzilishda 24 soatga cheklanasiz.';
  elsif cnt = 2 then
    insert into public.chat_bans (user_id, until, reason) values (p_user, now() + interval '24 hours', reason)
      on conflict (user_id) do update set until = excluded.until, reason = excluded.reason, created_at = now();
    return reason || '. Siz 24 soat chatga yoza olmaysiz.';
  else
    insert into public.chat_bans (user_id, until, reason) values (p_user, now() + interval '7 days', reason)
      on conflict (user_id) do update set until = excluded.until, reason = excluded.reason, created_at = now();
    return reason || '. Siz 7 kun chatga yoza olmaysiz. Keyingi buzilishda doimiy ban beriladi.';
  end if;
end $$;

create or replace function public.voice_left_today(p_user uuid) returns int
language sql stable security definer set search_path = '' as $$
  select greatest(0, 1 - count(*))::int from public.group_messages
  where user_id = p_user and kind = 'voice' and created_at >= public.moscow_day_start();
$$;

-- What the signed-in user may do in the group right now.
create or replace function public.group_me() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare uid uuid := auth.uid(); p record;
begin
  select role, created_at into p from public.profiles where id = uid;
  if not found then return jsonb_build_object('signed_in', false); end if;
  return jsonb_build_object(
    'signed_in', true,
    'user_id', uid,
    'is_admin', p.role = 'admin',
    'blocked_text', public.active_ban_text(uid),
    'text_only_until', case when p.role <> 'admin' and p.created_at + interval '24 hours' > now() then p.created_at + interval '24 hours' end,
    'voice_left_today', case when p.role = 'admin' then 99 else public.voice_left_today(uid) end
  );
end $$;

create or replace function public.raise_user_error(msg text) returns void
language plpgsql set search_path = '' as $$
begin
  raise exception using errcode = 'P0001', message = msg;
end $$;

-- Sends a message to a city group. Idempotent per (user, client_id) so retries never duplicate.
create or replace function public.group_send(
  p_city text, p_kind text, p_body text, p_client_id uuid,
  p_media_path text default null, p_thumb_path text default null, p_duration_sec int default null,
  p_reply_to bigint default null, p_width int default null, p_height int default null
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := auth.uid();
  me record;
  v_body text := trim(coalesce(p_body, ''));
  is_admin boolean;
  bt text;
  hash text;
  same int;
  rule text;
  target record;
  rec public.group_messages;
begin
  if uid is null then perform public.raise_user_error('Yozish uchun avval hisobga kiring'); end if;
  select * into rec from public.group_messages where user_id = uid and client_id = p_client_id;
  if found then return jsonb_build_object('message', to_jsonb(rec)); end if;

  select role, created_at, blocked_at into me from public.profiles where id = uid;
  if me.blocked_at is not null then perform public.raise_user_error('Hisobingiz bloklangan'); end if;
  is_admin := me.role = 'admin';
  if p_city not in ('moskva', 'spb') then perform public.raise_user_error('Guruh topilmadi'); end if;
  if p_kind not in ('text', 'image', 'video', 'voice') then perform public.raise_user_error('Noto‘g‘ri xabar turi'); end if;
  if char_length(v_body) > 2000 then perform public.raise_user_error('Xabar 2000 belgidan oshmasin'); end if;

  bt := public.active_ban_text(uid);
  if bt is not null then perform public.raise_user_error(bt); end if;

  if p_kind = 'text' and v_body = '' then perform public.raise_user_error('Xabar bo‘sh'); end if;
  if p_kind <> 'text' then
    if p_media_path is null then perform public.raise_user_error('Fayl biriktirilmagan'); end if;
    if not is_admin and me.created_at + interval '24 hours' > now() then
      perform public.raise_user_error('Yangi hisoblar birinchi 24 soat faqat matn yozadi');
    end if;
    if split_part(p_media_path, '/', 1) <> uid::text or (p_thumb_path is not null and split_part(p_thumb_path, '/', 1) <> uid::text) then
      perform public.raise_user_error('Fayl topilmadi');
    end if;
    if not exists (select 1 from storage.objects where bucket_id = 'chat-media' and name = p_media_path) then
      perform public.raise_user_error('Fayl yuklanmagan. Qayta urinib ko‘ring');
    end if;
  end if;
  if p_kind = 'video' and coalesce(p_duration_sec, 0) > 61 then perform public.raise_user_error('Video 60 soniyadan oshmasin'); end if;
  if p_kind = 'voice' then
    if coalesce(p_duration_sec, 0) > 31 then perform public.raise_user_error('Ovozli xabar 30 soniyadan oshmasin'); end if;
    if not is_admin and public.voice_left_today(uid) <= 0 then
      perform public.raise_user_error('Bugun ovozli xabar yuborib bo‘lgansiz. Ertaga yana yuborishingiz mumkin');
    end if;
  end if;

  if not is_admin and public.has_link(v_body) then perform public.raise_user_error('Havola joylash faqat admin uchun ruxsat etilgan'); end if;

  if char_length(v_body) >= 25 then
    hash := left(regexp_replace(public.norm_text(v_body), '[^[:alnum:]]+', '', 'g'), 400);
    if char_length(hash) < 20 then hash := null; end if;
  end if;
  if hash is not null and not is_admin then
    select count(*) into same from public.group_messages
      where user_id = uid and body_hash = hash and created_at >= public.moscow_day_start() and deleted_at is null;
    if same >= 3 then perform public.raise_user_error('Bu e’lon bugun 3 marta joylangan. Ertaga yana joylashingiz mumkin'); end if;
  end if;

  if not is_admin then
    rule := public.moderate_text(v_body);
    if rule is not null then
      -- the strike must be saved, so the refusal is returned instead of raised (raising rolls it back)
      return jsonb_build_object('error', public.apply_strike(uid, rule, coalesce(nullif(v_body, ''), p_kind), true));
    end if;
  end if;

  if p_reply_to is not null then
    select user_id, city into target from public.group_messages where id = p_reply_to and deleted_at is null;
    if not found or target.city <> p_city then perform public.raise_user_error('Javob berilayotgan xabar topilmadi'); end if;
  end if;

  insert into public.group_messages (city, user_id, client_id, kind, body, media_path, thumb_path, duration_sec, width, height, reply_to_id, body_hash)
  values (
    p_city, uid, p_client_id, p_kind, v_body, p_media_path,
    case when p_kind = 'video' then p_thumb_path end,
    case when p_kind in ('video', 'voice') then p_duration_sec end,
    case when p_kind in ('image', 'video') then p_width end,
    case when p_kind in ('image', 'video') then p_height end,
    p_reply_to, hash)
  returning * into rec;

  insert into public.group_members (user_id, city, last_read_at, updated_at) values (uid, p_city, now(), now())
    on conflict (user_id) do update set city = excluded.city, last_read_at = now(), updated_at = now();
  return jsonb_build_object('message', to_jsonb(rec));
end $$;

-- save / unsave / edit / delete / punish (admin) / pin / unpin / restore (admin)
create or replace function public.group_action(p_id bigint, p_action text, p_body text default null, p_rule text default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := auth.uid();
  adm boolean := public.is_admin();
  msg record;
  rule text;
  note text;
  b text := trim(coalesce(p_body, ''));
begin
  if uid is null then perform public.raise_user_error('Avval hisobga kiring'); end if;
  select * into msg from public.group_messages where id = p_id and deleted_at is null;
  if not found then perform public.raise_user_error('Xabar topilmadi'); end if;

  if p_action = 'save' then
    insert into public.group_saved (user_id, message_id) values (uid, p_id) on conflict do nothing;
  elsif p_action = 'unsave' then
    delete from public.group_saved where user_id = uid and message_id = p_id;
  elsif p_action = 'edit' then
    if msg.user_id <> uid then perform public.raise_user_error('Faqat o‘z xabaringizni tahrirlay olasiz'); end if;
    if b = '' and msg.kind = 'text' then perform public.raise_user_error('Xabar bo‘sh'); end if;
    if char_length(b) > 2000 then perform public.raise_user_error('Xabar 2000 belgidan oshmasin'); end if;
    note := public.active_ban_text(uid);
    if note is not null then perform public.raise_user_error(note); end if;
    if not adm then
      if public.has_link(b) then perform public.raise_user_error('Havola joylash faqat admin uchun ruxsat etilgan'); end if;
      rule := public.moderate_text(b);
      if rule is not null then return jsonb_build_object('error', public.apply_strike(uid, rule, b, true)); end if;
    end if;
    update public.group_messages set body = b, edited_at = now() where id = p_id;
  elsif p_action in ('delete', 'punish') then
    if p_action = 'delete' and msg.user_id <> uid and not adm then perform public.raise_user_error('Faqat o‘z xabaringizni o‘chira olasiz'); end if;
    if p_action = 'punish' and not adm then perform public.raise_user_error('Faqat admin uchun'); end if;
    -- the row stays (wiped) so every open chat removes it through Realtime
    update public.group_messages set deleted_at = now(), pinned_at = null, body = '', media_expired = true where id = p_id;
    if p_action = 'punish' then
      note := public.apply_strike(msg.user_id, coalesce(p_rule, 'card'), msg.body, false);
      return jsonb_build_object('ok', true, 'note', note, 'media', jsonb_build_array(msg.media_path, msg.thumb_path));
    end if;
    return jsonb_build_object('ok', true, 'media', jsonb_build_array(msg.media_path, msg.thumb_path));
  elsif p_action in ('pin', 'unpin', 'restore') then
    if not adm then perform public.raise_user_error('Faqat admin uchun'); end if;
    if p_action = 'pin' then
      update public.group_messages set pinned_at = null where city = msg.city and pinned_at is not null;
      update public.group_messages set pinned_at = now(), hidden_at = null where id = p_id;
    elsif p_action = 'unpin' then
      update public.group_messages set pinned_at = null where id = p_id;
    else
      update public.group_messages set hidden_at = null, report_count = 0 where id = p_id;
      delete from public.group_reports where message_id = p_id;
    end if;
  else
    perform public.raise_user_error('Noma’lum amal');
  end if;
  return jsonb_build_object('ok', true);
end $$;

-- 3 reports hide a message until an admin looks at it
create or replace function public.group_report(p_id bigint, p_reason text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare uid uuid := auth.uid(); msg record; cnt int;
begin
  if uid is null then perform public.raise_user_error('Avval hisobga kiring'); end if;
  select * into msg from public.group_messages where id = p_id and deleted_at is null;
  if not found then perform public.raise_user_error('Xabar topilmadi'); end if;
  if msg.user_id = uid then perform public.raise_user_error('O‘z xabaringizga shikoyat qilib bo‘lmaydi'); end if;
  insert into public.group_reports (message_id, reporter_id, reason) values (p_id, uid, left(p_reason, 100)) on conflict do nothing;
  select count(*) into cnt from public.group_reports where message_id = p_id;
  update public.group_messages set report_count = cnt,
    hidden_at = case when cnt >= 3 and pinned_at is null then coalesce(hidden_at, now()) else hidden_at end
    where id = p_id;
  return jsonb_build_object('ok', true);
end $$;

-- Marks the group read; other members see the second tick through Realtime on group_members
create or replace function public.group_mark_read(p_city text) returns timestamptz
language plpgsql security definer set search_path = '' as $$
declare uid uuid := auth.uid(); t timestamptz := now();
begin
  if uid is null or p_city not in ('moskva', 'spb') then return null; end if;
  insert into public.group_members (user_id, city, last_read_at, updated_at) values (uid, p_city, t, t)
    on conflict (user_id) do update set city = excluded.city, last_read_at = t, updated_at = t;
  update public.profiles set last_seen_at = t where id = uid;
  return t;
end $$;

-- Group header numbers + read state in one round trip
create or replace function public.group_state(p_city text) returns jsonb
language sql stable security definer set search_path = '' as $$
  select jsonb_build_object(
    'members', (select count(*) from public.group_members where city = p_city),
    'others_read_at', (select max(last_read_at) from public.group_members where city = p_city and user_id <> auth.uid()),
    'my_read_at', (select last_read_at from public.group_members where user_id = auth.uid() and city = p_city),
    'unread', (select count(*) from public.group_messages m where m.city = p_city and m.deleted_at is null and m.hidden_at is null
                and m.user_id <> auth.uid() and m.created_at > now() - interval '48 hours'
                and m.created_at > coalesce((select last_read_at from public.group_members where user_id = auth.uid() and city = p_city), now() - interval '48 hours')),
    'me', public.group_me()
  );
$$;

grant execute on function public.group_send, public.group_action, public.group_report, public.group_mark_read, public.group_state, public.group_me to authenticated;
revoke execute on function public.apply_strike, public.voice_left_today, public.active_ban_text from anon, authenticated, public;

